#!/bin/bash

BINARY="../bin/third"
PASS=0
FAIL=0

run_test() {
    local description="$1"
    local args="$2"
    local expected="$3"
    
    actual=$($BINARY $args 2>&1)
    
    if [ "$actual" = "$expected" ]; then
        echo "✓ PASS: $description"
        ((PASS++))
    else
        echo "✗ FAIL: $description"
        echo "  Ожидалось: $expected"
        echo "  Получено:  $actual"
        ((FAIL++))
    fi
}

run_test_contains() {
    local description="$1"
    local args="$2"
    local expected="$3"
    
    actual=$($BINARY $args 2>&1)
    
    if echo "$actual" | grep -q "$expected"; then
        echo "✓ PASS: $description"
        ((PASS++))
    else
        echo "✗ FAIL: $description"
        echo "  Ожидалось найти: $expected"
        echo "  Получено:  $actual"
        ((FAIL++))
    fi
}

echo "=== Тестирование задания third ==="

echo "--- Тесты флага -q (квадратное уравнение) ---"

run_test_contains "q_flag: два корня" "-q 0.001 1 -3 2" "уравнение содержит два корня"

run_test_contains "q_flag: один корень" "-q 0.001 1 -2 1" "уравнение содержит один корень"

run_test_contains "q_flag: нет корней" "-q 0.001 1 0 1" "уравнение не содержит действительных корней"

run_test_contains "q_flag: бесконечно много корней" "-q 0.001 0 0 0" "уравнение содержит бесконечное количество корней"

run_test_contains "q_flag: линейное уравнение" "-q 0.001 0 2 -4" "уравнение содержит единственный корень"

run_test_contains "q_flag: перестановки коэффициентов" "-q 0.001 1 2 3" "При a ="

run_test_contains "q_flag: несколько перестановок" "-q 0.001 1 2 3" "При a = 1.00000, b = 2.00000, c = 3.00000"

run_test_contains "q_flag: другая перестановка" "-q 0.001 1 2 3" "При a = 1.00000, b = 3.00000, c = 2.00000"

run_test_contains "q_flag: еще перестановка" "-q 0.001 1 2 3" "При a = 2.00000, b = 1.00000, c = 3.00000"

echo
echo "--- Тесты флага -m (кратность) ---"

run_test "m_flag: кратно" "-m 10 5" "Первое число кратно второму"

run_test "m_flag: не кратно" "-m 7 3" "Первое число не кратно второму"

run_test "m_flag: отрицательные числа кратно" "-m -10 5" "Первое число кратно второму"

run_test "m_flag: отрицательные числа не кратно" "-m -7 3" "Первое число не кратно второму"

run_test "m_flag: оба отрицательных кратно" "-m -10 -5" "Первое число кратно второму"

run_test "m_flag: делитель больше делимого" "-m 5 10" "Первое число не кратно второму"

run_test "m_flag: равные числа" "-m 5 5" "Первое число кратно второму"

run_test_contains "m_flag: деление на ноль" "-m 5 0" "Некорректно введенное число"

run_test_contains "m_flag: недостаточно аргументов" "-m 5" "Введено недостаточно аргументов"

echo
echo "--- Тесты флага -t (прямоугольный треугольник) ---"

run_test_contains "t_flag: прямоугольный треугольник 3-4-5" "-t 0.001 3 4 5" "могут быть длинами сторон прямоугольного треугольника"

run_test_contains "t_flag: прямоугольный треугольник 5-3-4" "-t 0.001 5 3 4" "могут быть длинами сторон прямоугольного треугольника"

run_test_contains "t_flag: не прямоугольный треугольник" "-t 0.001 2 3 4" "не могут быть длинами сторон прямоугольного треугольника"

run_test_contains "t_flag: равнобедренный прямоугольный" "-t 0.001 1 1 1.41421356" "могут быть длинами сторон прямоугольного треугольника"

run_test_contains "t_flag: недостаточно аргументов" "-t 0.001 3 4" "Введено недостаточно аргументов"

echo
echo "--- Тесты ошибок ---"

run_test_contains "некорректный флаг" "-x 5" "Введен некорректный флаг"

run_test_contains "некорректный флаг /x" "/x 5" "Введен некорректный флаг"

run_test_contains "недостаточно аргументов" "-q 5" "Введено недостаточно аргументов"

run_test_contains "некорректное число в q" "-q abc 1 2 3" "Некорректно введенное число"

run_test_contains "некорректное число в m" "-m abc 5" "Некорректно введенное число"

run_test_contains "некорректное число в t" "-t 0.001 abc 4 5" "Некорректно введенное число"

run_test_contains "отрицательный epsilon в q" "-q -0.001 1 2 3" "Некорректно введенное число"

run_test_contains "отрицательное число в t" "-t 0.001 -3 4 5" "Некорректно введенное число"

run_test_contains "два флага" "-q -m 5" "Может быть исполнен только один флаг"

echo
echo "Пройдено: $PASS | Провалено: $FAIL | Всего: $((PASS + FAIL))"

[ $FAIL -eq 0 ] && exit 0 || exit 1
